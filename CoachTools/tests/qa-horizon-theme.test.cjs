'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {parseHTML}=require('linkedom');
const labels=['Overall QA','Trend','Below Goal','Unreviewed','Coach / QA Gap','Coaching Reach'];
const {window,document}=parseHTML(`<html><head><meta name="coachtools-id" content="qa-scores"></head><body><div class="headerActions commandActions"></div><div id="kpiGrid">${labels.map(label=>`<div class="kpiCard"><div class="kpiLabel">${label}</div></div>`).join('')}</div></body></html>`);
const stored=new Map([['qaScores.kpiDrilldowns.v1',JSON.stringify({theme:'galactic',gapAbsolute:true})]]);
window.filterRows=()=>[];
const context={window,document,localStorage:{getItem:key=>stored.get(key)||null,setItem:(key,value)=>stored.set(key,value)},MutationObserver:class{observe(){}disconnect(){}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../shared/qa-scores-kpi-drilldowns.js'),'utf8'),context);
const toggle=document.getElementById('qaThemeToggle');
assert.ok(toggle,'QA color controls remain available.');
assert.equal(toggle.querySelector('[data-qa-theme="galactic"]').textContent,'Horizon');
assert.ok(document.body.classList.contains('qaGalactic'),'An existing saved dark theme is restored.');
assert.equal(toggle.querySelector('[data-qa-theme="galactic"]').getAttribute('aria-pressed'),'true');
toggle.querySelector('[data-qa-theme="light"]').dispatchEvent(new window.Event('click',{bubbles:true}));
assert.equal(document.body.classList.contains('qaGalactic'),false);
assert.equal(JSON.parse(stored.get('qaScores.kpiDrilldowns.v1')).theme,'light');
toggle.querySelector('[data-qa-theme="galactic"]').dispatchEvent(new window.Event('click',{bubbles:true}));
assert.equal(document.body.classList.contains('qaGalactic'),true);
assert.equal(JSON.parse(stored.get('qaScores.kpiDrilldowns.v1')).theme,'galactic','Horizon continues using the compatible stored value.');
assert.equal(JSON.parse(stored.get('qaScores.kpiDrilldowns.v1')).gapAbsolute,true,'Theme changes preserve other saved QA preferences.');
assert.equal(document.querySelectorAll('#kpiGrid [role="button"][tabindex="0"]').length,6,'Metric drilldown controls keep their keyboard affordances.');
console.log('QA Horizon theme persistence and control compatibility tests passed.');
