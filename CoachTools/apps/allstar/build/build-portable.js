#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const path=require('node:path');

const root=path.resolve(__dirname,'..');
const suiteRoot=path.resolve(root,'..','..');
function sourcePath(relative){ return path.join(root,relative); }
function suitePath(relative){ return path.join(suiteRoot,relative); }
const htmlPath=sourcePath('allstar.html');
const generatorPath=sourcePath(path.join('qualtrics','generator.html'));
const testsPath=sourcePath(path.join('tests','regression-tests.js'));
const carrierPath=sourcePath(path.join('qualtrics','generator-source.js'));
const distDir=path.join(root,'dist');
const outPath=sourcePath(path.join('dist','All-Star-Portable.html'));

function read(relative){ return fs.readFileSync(sourcePath(relative),'utf8'); }
function readSuite(relative){ return fs.readFileSync(suitePath(relative),'utf8'); }
function scriptLiteral(text){ return JSON.stringify(text).replace(/<\/script/gi,'<\\/script').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029'); }
function size(n){ return n<1024?n+' B':n<1024*1024?(n/1024).toFixed(1)+' KB':(n/1024/1024).toFixed(2)+' MB'; }
function validateBundledGenerator(html,label){
  for(const id of ['view-keyfiles','qaInput','coachingInput','checklistInput','weeklyStatsInput']) if(!html.includes('id="'+id+'"')) throw new Error(label+' is missing '+id+'.');
  for(const marker of ['els.qaInput.onchange=e=>loadQA','els.coachingInput.onchange=e=>loadCoaching','els.checklistInput.onchange=e=>loadChecklist','els.weeklyStatsInput.onchange=e=>loadWeeklyStats']) if(!html.includes(marker)) throw new Error(label+' is missing the Add 4 Key Files handler '+marker+'.');
  const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(match=>match[1]).filter(source=>source.trim());
  if(!scripts.length) throw new Error(label+' contains no executable scripts.');
  scripts.forEach((source,index)=>{ try{ new Function(source); }catch(error){ throw new Error(label+' embedded script '+(index+1)+' is invalid: '+(error.message||error)); } });
}

const insights=read('qualtrics/insights.js');
const individualMessages=read('qualtrics/individual-messages.js');
const individualUi=read('qualtrics/individual-ui.js');
const generatorRaw=fs.readFileSync(generatorPath,'utf8');
let generator=generatorRaw.replace(/<script src="insights\.js" onerror="[^"]*"><\/script>/,()=>'<script data-qualtrics-source="qualtrics/insights.js">\n'+insights.replace(/<\/script/gi,'<\\/script')+'\n<\/script>');
if(generator===generatorRaw) throw new Error('Qualtrics insights module script tag was not found for bundling.');
const beforeIndividualMessages=generator;
generator=generator.replace(/<script src="individual-messages\.js" onerror="[^"]*"><\/script>/,()=>'<script data-qualtrics-source="qualtrics/individual-messages.js">\n'+individualMessages.replace(/<\/script/gi,'<\\/script')+'\n<\/script>');
if(generator===beforeIndividualMessages) throw new Error('Qualtrics Individual Messages engine script tag was not found for bundling.');
const beforeIndividualUi=generator;
generator=generator.replace(/<script src="individual-ui\.js" onerror="[^"]*"><\/script>/,()=>'<script data-qualtrics-source="qualtrics/individual-ui.js">\n'+individualUi.replace(/<\/script/gi,'<\\/script')+'\n<\/script>');
if(generator===beforeIndividualUi) throw new Error('Qualtrics Individual Messages UI script tag was not found for bundling.');
validateBundledGenerator(generator,'Qualtrics carrier');
const carrier="/* GENERATED from qualtrics/generator.html by build/build-portable.js. Do not edit this file directly. */\n'use strict';\nwindow.__ALLSTAR_QUALTRICS_GENERATOR_HTML__="+JSON.stringify(generator)+";\n";
fs.writeFileSync(carrierPath,carrier);

let html=fs.readFileSync(htmlPath,'utf8');
for(const vendor of ['xlsx.full.min.js','html2pdf.bundle.min.js','jspdf.umd.min.js']){
  const marker='<script src="../../vendor/'+vendor+'"><\/script>';
  if(!html.includes(marker)) throw new Error('Portable vendor marker missing: '+vendor);
  html=html.replace(marker,'<script data-allstar-vendor="'+vendor+'">\n'+readSuite('vendor/'+vendor).replace(/<\/script/gi,'<\\/script')+'\n<\/script>');
}
for(const shared of ['coachtools-sync.js','coachtools-storage.js','coachtools-identity.js','coachtools-import.js','coachtools-close-policy.js','coachtools-shell.js']){
  const marker='<script src="../../shared/'+shared+'"><\/script>';
  if(!html.includes(marker)) throw new Error('Portable shared marker missing: '+shared);
  html=html.replace(marker,'<script data-coachtools-source="shared/'+shared+'">\n'+readSuite('shared/'+shared).replace(/<\/script/gi,'<\\/script')+'\n<\/script>');
}
html=html.replace(/<link rel="stylesheet" href="css\/allstar\.css">/,()=>'<style data-allstar-source="css/allstar.css">\n'+read('css/allstar.css')+'\n</style>');
let portableGenerator=generator;
portableGenerator=portableGenerator.replace(/<script src="\.\.\/\.\.\/vendor\/xlsx\.full\.min\.js" onerror="[^"]*"><\/script>/,'<script data-allstar-vendor="xlsx.full.min.js">window.XLSX=parent.XLSX;<\/script>');
portableGenerator=portableGenerator.replace(/<script src="\.\.\/\.\.\/vendor\/jszip\.min\.js" onerror="[^"]*"><\/script>/,()=>'<script data-allstar-vendor="jszip.min.js">\n'+readSuite('vendor/jszip.min.js').replace(/<\/script/gi,'<\\/script')+'\n<\/script>');
if(/\.\.\/vendor\/(?:xlsx|jszip)/.test(portableGenerator)) throw new Error('Portable Qualtrics generator still contains a vendor path.');
validateBundledGenerator(portableGenerator,'Portable Qualtrics srcdoc');
const assets='<script data-allstar-portable-assets>\nwindow.__ALLSTAR_QUALTRICS_GENERATOR_HTML__='+scriptLiteral(portableGenerator)+';\nwindow.__ALLSTAR_REGRESSION_TESTS_SOURCE__='+scriptLiteral(fs.readFileSync(testsPath,'utf8'))+';\n<\/script>\n';
const firstLocalScript=html.search(/<script src="js\//);
if(firstLocalScript<0) throw new Error('No local All-Star scripts were found in allstar.html.');
html=html.slice(0,firstLocalScript)+assets+html.slice(firstLocalScript);
html=html.replace(/<script src="(js\/[^"]+)"><\/script>/g,(match,relative)=>{
  const source=read(relative).replace(/<\/script/gi,'<\\/script');
  return '<script data-allstar-source="'+relative+'">\n'+source+'\n<\/script>';
});
const unresolvedDependencies=html.match(/(?:href="css\/[^"]+|src="js\/[^"]+)/g)||[];
if(unresolvedDependencies.length) throw new Error('Portable build still contains a first-party or suite dependency: '+unresolvedDependencies.slice(0,5).join(', '));
if(html.includes('patchQualtricsGeneratorSource')||html.includes('qualtricsGeneratorSource')) throw new Error('Portable build contains obsolete Qualtrics patch architecture.');
for(const marker of ['ALLSTAR_REPORT_SCHEMA_VERSION','runPreflight','allStarSavedReports.v1','ruleDisplayColumnEnabled','correctiveContextEnabled','Organization Opportunity Summary','QualtricsInsights','QualtricsIndividualMessages','individualMessageSettings.v1','allstar-clear-data','simpleQualtricsExecutiveMatrixHtml','displayColumnValue']){
  if(!html.includes(marker)) throw new Error('Portable build is missing required marker: '+marker);
}
fs.mkdirSync(distDir,{recursive:true});
fs.writeFileSync(outPath,html);
console.log('Generated '+outPath);
console.log('Portable size: '+size(fs.statSync(outPath).size));
console.log('Qualtrics carrier refreshed: '+size(fs.statSync(carrierPath).size));
